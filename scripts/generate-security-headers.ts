import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const DIST_DIR = 'dist';
const HEADER_FILE = join(DIST_DIR, '_headers');

const scriptHashes = new Set<string>();
const styleHashes = new Set<string>();
const styleAttributeHashes = new Set<string>();

const hashInlineContent = (content: string) =>
  `'sha256-${createHash('sha256').update(content, 'utf8').digest('base64')}'`;

const collectHtmlFiles = async (dir: string): Promise<string[]> => {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = join(dir, entry.name);

      if (entry.isDirectory()) {
        return collectHtmlFiles(fullPath);
      }

      return entry.isFile() && entry.name.endsWith('.html') ? [fullPath] : [];
    })
  );

  return files.flat();
};

const collectInlineHashes = (html: string) => {
  for (const match of html.matchAll(
    /<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi
  )) {
    const content = match[1];

    if (content.trim()) {
      scriptHashes.add(hashInlineContent(content));
    }
  }

  for (const match of html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)) {
    const content = match[1];

    if (content.trim()) {
      styleHashes.add(hashInlineContent(content));
    }
  }

  for (const match of html.matchAll(/\sstyle=(['"])(.*?)\1/gi)) {
    const content = match[2];

    if (content.trim()) {
      styleAttributeHashes.add(hashInlineContent(content));
    }
  }
};

const buildCsp = () => {
  const scriptSrc = ["'self'", ...scriptHashes].join(' ');
  const styleSrc = ["'self'", ...styleHashes].join(' ');

  return [
    "default-src 'self'",
    `script-src ${scriptSrc}`,
    `style-src ${styleSrc}`,
    `style-src-attr 'unsafe-hashes' ${Array.from(styleAttributeHashes).join(' ')}`,
    "img-src 'self' data: https://cdn.sanity.io",
    "font-src 'self' data:",
    "connect-src 'self' https://*.sanity.io",
    "worker-src 'self' blob:",
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "object-src 'none'",
  ].join('; ');
};

const main = async () => {
  const htmlFiles = await collectHtmlFiles(DIST_DIR);

  for (const file of htmlFiles) {
    collectInlineHashes(await readFile(file, 'utf8'));
  }

  const headers = `# Generated by scripts/generate-security-headers.ts.
# Do not edit dist/_headers directly.

/*
  Content-Security-Policy: ${buildCsp()}
  Strict-Transport-Security: max-age=31536000
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), accelerometer=(), gyroscope=(), magnetometer=()
  Access-Control-Allow-Origin: https://biomed.kangwon.ac.kr
  Access-Control-Allow-Methods: GET, HEAD
`;

  await writeFile(HEADER_FILE, headers);
  console.log(
    `Generated ${HEADER_FILE} with ${scriptHashes.size} script hashes and ${styleHashes.size} style hashes.`
  );
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
